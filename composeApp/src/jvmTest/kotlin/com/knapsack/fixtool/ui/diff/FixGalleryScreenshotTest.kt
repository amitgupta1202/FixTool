/**
 * **The fix gallery: one picture per repair the surface offers, before and after.**
 *
 * These are living documentation, regenerated by every test run into `build/scenario-screenshots/` —
 * `fixes_NN_<kind>_offer.png` shows the affordance on the failure it repairs, `fixes_NN_<kind>_applied.png`
 * shows the surface after one click. Each test asserts the affordance exists before photographing it, so a
 * renamed tag or a withdrawn offer fails the build loudly instead of silently producing a gallery of
 * yesterday's UI. (Screenshots caught D1 when no assertion did — the argument for keeping pictures in the
 * suite at all. Tooltip text is deliberately absent here: tooltips need a hover the harness cannot hold
 * through a capture, and their wording is pinned by ReconcileSessionTest instead.)
 *
 * Fixtures are deliberately minimal — two to seven rows — so each image is about exactly one thing.
 */
class FixGalleryScreenshotTest {
    @get:Rule
    val composeTestRule = createComposeRule()

    private val dictionary = FixDictionaryAdapter.forVersion(FixVersion.FIX_4_4)
    private val arrival: Instant = Instant.parse("2026-07-14T09:35:44Z")
    private val outDir = File("build/scenario-screenshots").absoluteFile

    private fun ComposeContentTestRule.surface(
        initial: Expectation,
        message: MessageView,
        height: Dp = 340.dp,
    ) {
        setContent {
            var expectation by remember { mutableStateOf(initial) }
            val session =
                remember(Unit) {
                    ReconcileSession(
                        original = expectation,
                        initialReference =
                            ReferenceMessage.live(
                                message,
                                ReferenceMessage.Provenance.THIS_RUN,
                                "received — this run · 09:35:44",
                                arrival,
                            ),
                        dictionary = dictionary,
                        onChange = { expectation = it },
                    )
                }
            Box(modifier = Modifier.size(1180.dp, height).background(AppTheme.Colors.background)) {
                DiffSurface(session, crumb = "fix gallery › Step 2 · Expect ExecutionReport (8)")
            }
        }
    }

    private fun snap(name: String) {
        try {
            outDir.mkdirs()
            // The FIRST root: an open autocomplete popup (07's tag picker) is a second root window, and
            // onRoot() refuses to choose. The surface's own window is always the first.
            val image = composeTestRule.onAllNodes(isRoot()).onFirst().captureToImage()
            ImageIO.write(image.toAwtImage(), "png", File(outDir, "$name.png"))
        } catch (e: Exception) {
            println("[FixGallery] snapshot '$name' skipped: ${e.message}")
        }
    }

    private fun open(vararg fields: FieldExpectation) =
        Expectation(fields.toList(), messageType = "8", mode = MatchMode.OPEN)

    private fun click(tag: String) {
        composeTestRule.onNodeWithTag(tag).assertIsDisplayed()
        composeTestRule.onNodeWithTag(tag).performClick()
        composeTestRule.waitForIdle()
    }

    /** `«` on a value mismatch: re-baseline to what actually arrived, keeping the kind of matcher it is. */
    @Test
    fun `01 accept actual`() {
        composeTestRule.surface(
            open(FieldExpectation(35, Matcher.Exact("8")), FieldExpectation(151, Matcher.Numeric(0.0))),
            wireView(35 to "8", 151 to "500000"),
        )
        composeTestRule.onNodeWithTag("accept_actual-151-0").assertIsDisplayed()
        snap("fixes_01_accept_actual_offer")
        click("accept_actual-151-0")
        snap("fixes_01_accept_actual_applied")
    }

    /** `±` on numeric drift: the smallest band covering both sides, around the author's own baseline. */
    @Test
    fun `02 loosen to a covering band`() {
