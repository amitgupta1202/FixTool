    /** A drifted price, a drifted fill, a reformatted quantity and a late timestamp — the fix plan's whole range. */
    private val drifted =
        open(
            FieldExpectation(35, Matcher.Exact("8")),
            FieldExpectation(6, Matcher.Exact("1.09244")),
            FieldExpectation(31, Matcher.Numeric(1.09244)),
            FieldExpectation(38, Matcher.Exact("1000000")),
            FieldExpectation(60, Matcher.Temporal(TemporalKind.NOW_WITHIN_TOLERANCE, 60)),
        )
    private val driftedReply =
        wireView(
            35 to "8",
            6 to "1.09139",
            31 to "1.09139",
            38 to "1000000.0",
            // Five minutes after the arrival instant the rows are judged at: outside ±60s, inside ±300s.
            60 to "20260714-09:40:44",
        )

    /** "± fix 4…" → the sheet: two covering bands, a formatting repair, a temporal rung — applied as ONE edit. */
    @Test
    fun `09 fix plan with covering bands`() {
        composeTestRule.surface(drifted, driftedReply, height = 460.dp)
        click("diff-fix-plan")
        composeTestRule.onNodeWithTag("diff-fix-row-60").assertIsDisplayed()
        snap("fixes_09_fix_plan_sheet")
        click("diff-fix-apply")
        snap("fixes_09_fix_plan_applied")
    }

    /** The knob: one uniform tolerance — and the rows it cannot reach are marked "stay red", never hidden. */
